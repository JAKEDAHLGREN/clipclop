const { app, BrowserWindow, Tray, Menu, clipboard, ipcMain, nativeImage, screen, globalShortcut } = require("electron");
const path = require("path");
const ClipboardStore = require("./store");

const HISTORY_DIR = path.join(app.getPath("home"), ".clipclop");
const HISTORY_FILE = path.join(HISTORY_DIR, "history.json");
const POLL_INTERVAL = 300;
const CURSOR_OFFSET = 12;

// Password managers (1Password, Bitwarden, etc.) tag sensitive copies with these
// pasteboard types (see nspasteboard.org). Clips carrying them are never saved.
const IGNORED_PASTEBOARD_TYPES = [
  "org.nspasteboard.ConcealedType",
  "org.nspasteboard.TransientType",
  "org.nspasteboard.AutoGeneratedType",
];

const store = new ClipboardStore({ filePath: HISTORY_FILE });

let tray = null;
let popover = null;
let lastClipboardText = "";
let pollTimer = null;

function addClip(text) {
  store.add(text);
  broadcastClips();
}

function broadcastClips() {
  if (popover && popover.webContents && !popover.isDestroyed()) {
    popover.webContents.send("clips-updated", store.getAll());
  }
}

function isConcealedClipboard() {
  try {
    const formats = clipboard.availableFormats();
    return IGNORED_PASTEBOARD_TYPES.some(
      (type) => formats.includes(type) || clipboard.has(type)
    );
  } catch (_) {
    return false;
  }
}

function startClipboardMonitor() {
  try {
    lastClipboardText = clipboard.readText();
  } catch (_) {
    lastClipboardText = "";
  }
  pollTimer = setInterval(() => {
    try {
      const current = clipboard.readText();
      if (current && current !== lastClipboardText) {
        lastClipboardText = current;
        if (isConcealedClipboard()) return;
        addClip(current);
      }
    } catch (err) {
      console.error("Clipboard poll error:", err);
    }
  }, POLL_INTERVAL);
}

function stopClipboardMonitor() {
  if (pollTimer) {
    clearInterval(pollTimer);
    pollTimer = null;
  }
}

function createPopover() {
  popover = new BrowserWindow({
    width: 400,
    height: 500,
    frame: false,
    alwaysOnTop: true,
    show: false,
    skipTaskbar: true,
    resizable: false,
    webPreferences: {
      preload: path.join(__dirname, "preload.js"),
      contextIsolation: true,
      nodeIntegration: false,
    },
  });

  popover.loadFile(path.join(__dirname, "src", "index.html"));
  popover.webContents.setWindowOpenHandler(() => ({ action: "deny" }));
  popover.webContents.on("will-navigate", (e) => e.preventDefault());

  popover.on("blur", () => {
    if (popover && !popover.isDestroyed()) {
      if (popover.webContents.isDevToolsOpened()) {
        return;
      }
      popover.hide();
    }
  });
}

// Opens the list just to the right of the mouse cursor (hotkey). Flips to the
// left of the cursor near the right screen edge and shifts up near the bottom,
// always staying inside the work area of whichever display the cursor is on.
function positionPopoverNearCursor() {
  if (!popover) return;
  try {
    const cursor = screen.getCursorScreenPoint();
    const { workArea } = screen.getDisplayNearestPoint(cursor);
    const [width, height] = popover.getSize();
    let x = cursor.x + CURSOR_OFFSET;
    if (x + width > workArea.x + workArea.width) {
      x = cursor.x - CURSOR_OFFSET - width;
    }
    let y = cursor.y;
    const maxX = workArea.x + workArea.width - width;
    const maxY = workArea.y + workArea.height - height;
    x = Math.max(workArea.x, Math.min(x, maxX));
    y = Math.max(workArea.y, Math.min(y, maxY));
    popover.setPosition(Math.round(x), Math.round(y));
  } catch (err) {
    console.error("Failed to position popover at cursor:", err);
  }
}

function positionPopoverBelowTray() {
  if (!tray || !popover) return;
  try {
    const trayBounds = tray.getBounds();
    const [width, height] = popover.getSize();
    const display = screen.getDisplayMatching(trayBounds);
    let x = Math.round(trayBounds.x + trayBounds.width / 2 - width / 2);
    let y = Math.round(trayBounds.y + trayBounds.height + 4);
    if (x + width > display.bounds.x + display.bounds.width) {
      x = display.bounds.x + display.bounds.width - width;
    }
    if (x < display.bounds.x) {
      x = display.bounds.x;
    }
    if (y + height > display.bounds.y + display.bounds.height) {
      y = trayBounds.y - height - 4;
    }
    popover.setPosition(x, y);
  } catch (err) {
    console.error("Failed to position popover:", err);
  }
}

function positionPopover(anchor) {
  if (anchor === "cursor") {
    positionPopoverNearCursor();
  } else {
    positionPopoverBelowTray();
  }
}

function revealPopover(anchor) {
  positionPopover(anchor);
  if (process.platform === "darwin") app.show();
  popover.show();
  popover.focus();
  // Tells the renderer to reset: clear search, select the first item, focus input.
  popover.webContents.send("popover-shown", store.getAll());
}

function showPopover(anchor = "tray") {
  if (!popover || popover.isDestroyed()) {
    createPopover();
    popover.once("ready-to-show", () => revealPopover(anchor));
    return;
  }
  revealPopover(anchor);
}

function togglePopover(anchor = "tray") {
  if (popover && !popover.isDestroyed() && popover.isVisible()) {
    hidePopover();
    return;
  }
  showPopover(anchor);
}

function hidePopover() {
  if (!popover || popover.isDestroyed() || !popover.isVisible()) return;
  popover.hide();
  // Hand focus back to the app the user was in, so ⌘V pastes straight there.
  if (process.platform === "darwin") app.hide();
}

function buildTrayMenu() {
  // Login items only make sense for the installed .app, not `npm start`.
  const canSetLogin = app.isPackaged;
  const openAtLogin = canSetLogin && app.getLoginItemSettings().openAtLogin;
  return Menu.buildFromTemplate([
    { label: "Open ClipClop", click: () => showPopover("tray") },
    { type: "separator" },
    {
      label: "Launch at Login",
      type: "checkbox",
      checked: openAtLogin,
      enabled: canSetLogin,
      click: (item) => app.setLoginItemSettings({ openAtLogin: item.checked }),
    },
    { type: "separator" },
    { label: "Quit ClipClop", click: () => app.quit() },
  ]);
}

function setupIpc() {
  ipcMain.handle("copy-to-clipboard", (_event, args) => {
    try {
      const id = args?.id;
      if (typeof id !== "string") return { success: false };
      // Move the picked clip to the top of the history, then close the list.
      const clip = store.promote(id);
      if (!clip) {
        return { success: false };
      }
      clipboard.writeText(clip.content);
      lastClipboardText = clip.content;
      broadcastClips();
      hidePopover();
      return { success: true };
    } catch (err) {
      console.error("copy-to-clipboard error:", err);
      return { success: false };
    }
  });

  ipcMain.handle("hide-popover", () => {
    hidePopover();
    return { success: true };
  });

  ipcMain.handle("get-clips", () => {
    return store.getAll();
  });

  ipcMain.handle("delete-clip", (_event, args) => {
    try {
      const id = args?.id;
      if (typeof id !== "string") return { success: false };
      if (!store.deleteById(id)) {
        return { success: false };
      }
      broadcastClips();
      return { success: true };
    } catch (err) {
      console.error("delete-clip error:", err);
      return { success: false };
    }
  });

  ipcMain.handle("clear-all", () => {
    try {
      store.clear();
      broadcastClips();
      return { success: true };
    } catch (err) {
      console.error("clear-all error:", err);
      return { success: false };
    }
  });
}

app.whenReady().then(() => {
  const gotLock = app.requestSingleInstanceLock();
  if (!gotLock) {
    app.quit();
    return;
  }

  if (process.platform === "darwin") {
    app.dock.hide();
  }

  const iconPath = path.join(__dirname, "assets", "icon.png");
  let icon;
  try {
    icon = nativeImage.createFromPath(iconPath);
  } catch (_) {
    icon = nativeImage.createEmpty();
  }
  tray = new Tray(icon);
  tray.setToolTip("ClipClop");
  tray.on("click", () => {
    togglePopover("tray");
  });
  tray.on("right-click", () => {
    tray.popUpContextMenu(buildTrayMenu());
  });

  setupIpc();
  store.load();
  startClipboardMonitor();

  const shortcutRegistered = globalShortcut.register("CommandOrControl+Shift+V", () => {
    togglePopover("cursor");
  });
  if (!shortcutRegistered) {
    console.warn("Failed to register global shortcut CommandOrControl+Shift+V");
  }
});

app.on("will-quit", () => {
  globalShortcut.unregisterAll();
  stopClipboardMonitor();
});

app.on("second-instance", () => {
  showPopover("tray");
});
